/**
 * Every /api/v1 endpoint, described once (D92). The docs page and openapi.json are generated from this list, and a test
 * fails if a route file exists that isn't listed here (or the other way round).
 */
export type Access =
  | "public"
  | "signed-in"
  | "owner-admin"
  | "owner"
  | "roster-editor"
  | "uploader"
  /** A parent's shop session: the httpOnly cookie a code opens (ADR 0022). No account. */
  | "parent"
  | "internal";

export const ROUTE_GROUPS = [
  "Account",
  "Team",
  "Studio",
  "Jobs",
  "Roster",
  "Photos",
  "Products",
  "Payouts",
  "Taxes",
  "Orders",
  "Contacts",
  "Search",
  "Notifications",
  "Shop",
  "Internal",
] as const;

export interface RouteSpec {
  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
  path: string;
  group: (typeof ROUTE_GROUPS)[number];
  summary: string;
  description?: string;
  access: Access;
  /** Query string parameters, for lists. */
  query?: z.ZodObject;
  body?: z.ZodType;
  /** The body may be left out (e.g. an upload of individual photos). */
  bodyOptional?: boolean;
  success: {
    status: 200 | 201 | 202 | 204;
    schema?: z.ZodType;
    description: string;
    /** A file instead of JSON (e.g. the QR card PDF). */
    contentType?: "application/pdf";
    /** Response headers worth knowing, by name. */
    headers?: Record<string, string>;
  };
  errors: ApiErrorCode[];
}

